<#
.SYNOPSIS
    Regenerates the spend-rate chart meters in the Large layout.

.DESCRIPTION
    ClaudeLune by Lunez (luneswan).

    The chart is forty-eight Shape lines that differ only by an index: a trough
    for every hour, and a column drawn over it. Rainmeter has no loop, so they
    have to exist one per line, and editing them by hand means editing the same
    expression forty-eight times and getting it right every time.

    This writes them instead. Change the expression here, run it, and the layout
    is rebuilt. Everything outside the trend block is left exactly as it was, so
    this is safe to run against a layout that has been edited elsewhere.

    Nothing else calls this. It is a maintenance tool rather than part of the
    build, and the generated layout is committed like any other source file. The
    test suite runs it with -Check so the two cannot drift apart unnoticed.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File build\New-LuneTrendMeters.ps1

.EXAMPLE
    # Check that the committed layout still matches what this would produce.
    powershell -NoProfile -ExecutionPolicy Bypass -File build\New-LuneTrendMeters.ps1 -Check

.NOTES
    Copyright (c) Lunez (luneswan). MIT licence - see LICENSE.
#>

[CmdletBinding()]
param(
    # Report whether the layout is up to date and change nothing. Exits 1 if not.
    [switch]$Check,

    # One column per hour of the window the poller publishes.
    [ValidateRange(4, 48)]
    [int]$Columns = 24
)

$ErrorActionPreference = 'Stop'

$repoRoot   = Split-Path $PSScriptRoot -Parent
$layoutPath = Join-Path $repoRoot 'Skins\ClaudeLune\@Resources\Layouts\LuneLarge.inc'

# The trend block is everything between these two banners. Both are load-bearing:
# the generator replaces what lies between them and copies the rest untouched.
$startMark = '; =================================================================== trend ===='
$endMark   = '; ================================================================== footer ===='

function New-LuneShapeKey {
    param([int]$Index)
    # Rainmeter numbers the first shape "Shape", not "Shape1".
    if ($Index -eq 0) { return 'Shape' }
    return "Shape$($Index + 1)"
}

function New-LuneTrendBlock {
    param([int]$Columns)

    $header = @"
$startMark
; $Columns columns, one per hour of the last day. Each is the share of the weekly
; allowance spent in that hour, so a working session stands up and a quiet night
; lies flat.
;
; The troughs are drawn for every hour, filled or not. A chart that renders
; nothing at all during a quiet night reads as broken; a row of faint troughs
; reads as an idle day, which is what it is, and it gives the filled columns
; something to stand in.
;
; Each hour is its own meter so it can carry its own tooltip. Hovering a column
; names the hour it covers and what was spent in it.
;
; Generated by build\New-LuneTrendMeters.ps1. Edit that, not these lines.
[TrendCaption]
Meter=String
X=#Pad#
Y=#TrendCapY#
FontFace=#FontFace#
FontSize=#SmallFS#
FontColor=#Dim#
Text=Spend rate
; Bounded so it truncates instead of running into the value.
W=(#BarW# * 0.6)
H=(#SmallFS# * 2)
ClipString=1
AntiAlias=1
DynamicVariables=1

[TrendValue]
Meter=String
X=(#W# - #Pad#)
Y=#TrendCapY#
FontFace=#FontFace#
FontSize=#SmallFS#
FontWeight=600
FontColor=#Accent#
StringAlign=Right
Text=#SparkRange#
; Bounded so it truncates instead of running into the caption.
W=(#BarW# * 0.4)
H=(#SmallFS# * 2)
ClipString=1
AntiAlias=1
DynamicVariables=1
Group=Live
ToolTipTitle=Spend rate
ToolTipText=#SparkRange#, peak #TrendPeak#%/h#CRLF##TrendCovered# of #TrendCols# hours recorded

"@

    <#
    One meter per hour, rather than one meter holding every shape.

    Rainmeter attaches a tooltip to a meter, not to a shape inside it, so a single
    chart meter can only ever say one thing about the whole day. Splitting it lets
    each column name the hour it covers when you hover it.

    Each meter draws its own trough and its own column, so the full height of the
    strip is hoverable even for an hour with no reading, where the column itself
    has no width to hit.
    #>
    $columnBlocks = 0..($Columns - 1) | ForEach-Object {
        $spark  = "#Spark$($_ + 1)#"
        $height = "(#TrendH# * Clamp($spark,0,100) / 100)"
        @"
[TrendCol$($_ + 1)]
Meter=Shape
X=(#Pad# + (#TrendColW# * $_))
Y=#TrendY#
Shape=Rectangle 0,0,#TrendBarW#,#TrendH#,#TrendR# | Fill Color #AccentGhost# | StrokeWidth 0
Shape2=Rectangle 0,(#TrendH# - $height),(#TrendBarW# * ($spark > 0)),(Max(0,$height)),#TrendR# | Fill LinearGradient TrendGrad | StrokeWidth 0
TrendGrad=90 | #Accent# ; 0.0 | #AccentSoft# ; 1.0
DynamicVariables=1
Group=Live
ToolTipTitle=Spend rate
ToolTipText=#SparkTip$($_ + 1)#
"@
    }

    return (@($header, ($columnBlocks -join "`r`n")) -join "`r`n") + "`r`n"
}

$existing = [System.IO.File]::ReadAllText($layoutPath)
$startAt  = $existing.IndexOf($startMark)
$endAt    = $existing.IndexOf($endMark)
if ($startAt -lt 0) { throw "The trend banner is missing from $layoutPath." }
if ($endAt -le $startAt) { throw "The footer banner is missing or precedes the trend banner in $layoutPath." }

$rebuilt = $existing.Substring(0, $startAt) + (New-LuneTrendBlock -Columns $Columns) + $existing.Substring($endAt)

if ($Check) {
    if ($rebuilt -eq $existing) {
        Write-Host "LuneLarge.inc is up to date ($Columns columns)." -ForegroundColor Green
        exit 0
    }
    Write-Host 'LuneLarge.inc does not match the generator. Run this script without -Check.' -ForegroundColor Red
    exit 1
}

if ($rebuilt -eq $existing) {
    Write-Host "LuneLarge.inc already matches ($Columns columns); nothing written." -ForegroundColor Green
    exit 0
}

# UTF-8 without a BOM. Set-Content -Encoding UTF8 adds one on PowerShell 5.1, and
# Rainmeter then reads the leading section header with the BOM attached, parses
# no keys, finds no meters, and deactivates the skin outright.
[System.IO.File]::WriteAllText($layoutPath, $rebuilt, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "LuneLarge.inc rebuilt with $Columns columns." -ForegroundColor Green
